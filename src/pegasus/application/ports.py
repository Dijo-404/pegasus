"""Contracts owned by the use cases; external adapters satisfy them structurally."""

from typing import Protocol


class CommerceProvider(Protocol):
    async def search(self, query: str, country: str, intent: str) -> list[dict]: ...
    async def details(self, product_id: str) -> dict: ...
    async def create_invoice(self, action: dict) -> dict: ...
    async def invoice(self, invoice_id: str, access_token: str | None = None) -> dict: ...


class CommerceRepository(Protocol):
    def insert_intent(self, intent: dict) -> None: ...
    def intent(self, intent_id: str) -> dict: ...
    def save_intent(self, intent: dict) -> None: ...
    def list_intents(self) -> list[dict]: ...
    def approve(self, intent_id: str, expected_digest: str, ttl: int) -> tuple[str, int]: ...
    def reserve(self, intent_id: str, claims: dict, day: str, daily_cap: int) -> dict: ...
    def audit(self, intent_id: str) -> list[dict]: ...
    def event(self, intent_id: str, action: str, reason: str) -> None: ...


class PrivateOrderRepository(Protocol):
    def insert_private(self, order: dict) -> None: ...
    def private(self, order_id: str) -> dict: ...
    def confirm_private(self, order_id: str, payment: dict) -> dict: ...
    def redeem(self, order_id: str) -> None: ...


class GrantAuthority(Protocol):
    def sign(self, claims: dict) -> str: ...
    def verify(self, token: str) -> dict: ...


class PaymentVerifier(Protocol):
    async def address(self) -> str: ...
    async def find_payment(self, memo: str, amount_zats: int) -> dict | None: ...
    def payment_uri(self, address: str, amount_zats: int, memo: str) -> str: ...
